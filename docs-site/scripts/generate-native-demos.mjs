/*
 * Copies the React Native demos from native-playground/demos into this site,
 * so /native can render the real native components in the browser through
 * react-native-web.
 *
 * The demos import components by folder (`../../source/components/button`).
 * In the app Metro picks `index.native.ts` from that folder; a browser bundler
 * would pick the web `index.ts`. So each such import is rewritten to name the
 * native entry explicitly. Nothing else in the demos changes.
 *
 * Writes (never edit by hand):
 *   native-preview/generated/demos/*.tsx   rewritten copies of the demos
 *   native-preview/generated/registry.tsx  lazy loaders, one per demo export
 *
 * Run by `npm run dev` and `npm run build`; also `npm run gen:native`.
 */
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const repo = path.resolve(root, "..");
const DEMOS = path.join(repo, "native-playground", "demos");
const OUT = path.join(root, "native-preview", "generated");
const OUT_DEMOS = path.join(OUT, "demos");

const BANNER = "// Generated by scripts/generate-native-demos.mjs from native-playground/demos — do not edit.\n// @ts-nocheck\n";

/** Files that are app scaffolding, not demos. */
const SKIP = new Set(["Gallery.tsx"]);

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT_DEMOS, { recursive: true });

if (!fs.existsSync(DEMOS)) {
  console.warn("generate-native-demos: native-playground/demos not found; writing an empty registry");
}

const files = fs.existsSync(DEMOS)
  ? fs.readdirSync(DEMOS).filter((f) => f.endsWith(".tsx") && !SKIP.has(f))
  : [];

/** `../../source/...` from a demo, pointed at the same file from the generated copy. */
function rewrite(specifier) {
  if (!specifier.startsWith("../../source/")) return specifier;
  const target = path.resolve(DEMOS, specifier);
  let resolved = target;
  if (fs.existsSync(target) && fs.statSync(target).isDirectory()) {
    // Prefer the native entry, as Metro does.
    const native = ["index.native.ts", "index.native.tsx", "index.ts", "index.tsx"].find((f) =>
      fs.existsSync(path.join(target, f)),
    );
    if (native) resolved = path.join(target, native.replace(/\.tsx?$/, ""));
  }
  let rel = path.relative(OUT_DEMOS, resolved).split(path.sep).join("/");
  if (!rel.startsWith(".")) rel = `./${rel}`;
  return rel;
}

const exportsByFile = {};
for (const file of files) {
  const source = fs.readFileSync(path.join(DEMOS, file), "utf8");
  const rewritten = source.replace(/(from\s+["'])([^"']+)(["'])/g, (_, a, spec, b) => `${a}${rewrite(spec)}${b}`);
  fs.writeFileSync(path.join(OUT_DEMOS, file), BANNER + rewritten);
  const names = [...source.matchAll(/export\s+function\s+([A-Z]\w*Demo)\b/g)].map((m) => m[1]);
  if (names.length) exportsByFile[file.replace(/\.tsx$/, "")] = names;
}

const entries = Object.entries(exportsByFile).flatMap(([module, names]) =>
  names.map(
    (name) =>
      `  ${name}: () => import("./demos/${module}").then((m) => ({ default: m.${name} as ComponentType })),`,
  ),
);

fs.writeFileSync(
  path.join(OUT, "registry.tsx"),
  `${BANNER}import type { ComponentType } from "react";

/** Every native demo, loaded on demand. Keys are the demo export names. */
export const nativeDemos: Record<string, () => Promise<{ default: ComponentType }>> = {
${entries.join("\n")}
};
`,
);

console.log(`generate-native-demos: ${entries.length} demos from ${files.length} files`);
